    protected $_keys = [];
    function getAnnotationsMap()
    {
        if($this->_keys) {
            return $this->_keys;
        }
        $psth = $this->pdo->query("SELECT `alert_name` `key`, annotation_summary name FROM  c_events_alertmanager_rules order by 1");
        $resp = [];
        foreach ($psth->fetchAll() as $r) {
            $resp[$r['key']] = $r['name'];
        }
        $this->_keys = $resp;
        return $resp;
    }

    /**
     * @param $days
     * @return Event[]
     */
    function getForRetentionByDays($days, $limit = 10000)
    {
        $psth = $this->pdo->prepare("SELECT *
FROM c_events
WHERE created_at <= NOW() - INTERVAL ? DAY and resolved_at is not null limit ?");
        $psth->execute([$days, $limit]);
        $data = [];
        foreach ($psth->fetchAll() as $d) {
            $data[] = $this->fillByArr(new Event(), $d);
        }
        return $data;
    }
