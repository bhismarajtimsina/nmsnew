    function getSeverityStat($notResolved = true, User $user = null)
    {
        $where = " 1 = 1 ";
        if ($notResolved) {
            $where .= " and resolved_at is null ";
        }
        if($user) {
            if($user->getRole()->getId() > 0 && !in_array('events_see_all', $user->getRole()->getPermissions())) {
                $deviceGroupIds = [-100];
                foreach ($user->getDeviceGroups() as $gr) {
                    $deviceGroupIds[] = $gr->getId();
                }
                $where .= " and device_id in (SELECT id FROM devices WHERE group_id in (".join(",", $deviceGroupIds)."))";
            }
        }

        $query = "SELECT count(*) count, severity
                FROM c_events
                WHERE $where
                GROUP BY  severity";
        $resp = [
            'INFO' => 0,
            'WARNING' => 0,
            'CRITICAL' => 0,
        ];
        foreach ($this->pdo->query($query)->fetchAll() as $elem) {
            $resp[$elem['severity']] = (int)$elem['count'];
        }
        return $resp;
    }

